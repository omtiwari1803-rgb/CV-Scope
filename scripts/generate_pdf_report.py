    with open(MD_FILE, "r", encoding="utf-8") as f:
        md_text = f.read()

    # Convert markdown to HTML with tables, code fences, etc.
    html_body = markdown.markdown(
        md_text,
        extensions=["tables", "fenced_code", "toc", "nl2br", "sane_lists"]
    )

