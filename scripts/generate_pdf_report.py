def convert_html_to_pdf() -> None:
    """Use Microsoft Edge headless to print styled HTML to PDF."""
    if not EDGE_EXE.exists():
        raise FileNotFoundError(f"Microsoft Edge executable not found at {EDGE_EXE}")

    cmd = [
        str(EDGE_EXE),
        "--headless",
        "--disable-gpu",
        "--no-pdf-header-footer",
        "--run-all-compositor-stages-before-draw",
        "--virtual-time-budget=4000",
        f"--print-to-pdf={PDF_FILE.resolve()}",
        str(HTML_FILE.resolve())
    ]

    print("Executing Microsoft Edge headless PDF rendering...")
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"Edge stderr: {res.stderr}", file=sys.stderr)
        raise RuntimeError(f"Edge failed with return code {res.returncode}")

    if PDF_FILE.exists() and PDF_FILE.stat().st_size > 0:
        print(f"SUCCESS: Generated PDF Report ({PDF_FILE.stat().st_size / 1024:.1f} KB): {PDF_FILE}")
    else:
        raise RuntimeError("PDF file was not created or is empty.")


if __name__ == "__main__":
    convert_md_to_html()
    convert_html_to_pdf()
